import type { NavItem } from "@/lib/navigation";

import { NavLink } from "./NavLink";

/**
 * 이 사이트의 화면 메뉴 — 머리말 **안**에 늘어서는 알약 단추들.
 *
 * ── 🔴 2026-09-21: 머리말 **아래 띠**에서 머리말 **안**으로 옮겼다 ──────
 * 사용자 지정: "PO의 메뉴바는 휴가관리에서 메뉴바 안에 버튼들이 있었던 것 처럼
 * 만들어줘". 전에는 머리말 아래 제 테두리를 가진 띠였는데, 그러면 화면 맨 위가
 * **두 층**이 되어 본문이 한 줄만큼 줄어든다 — 2026-09-18 에 서비스 메뉴바를
 * 머리말 **위**에서 **안**으로 넣은 것과 **같은 까닭, 같은 방향**이다
 * ((app)/layout.tsx 의 ServiceMenuBar 주석).
 *
 * 함께 달라진 것 둘:
 *  1. 글자 링크 → **알약 단추**(components/NavLink.tsx).
 *  2. 🔴 **지금 보고 있는 화면이 짙게 칠해진다.** 전에는 `/quotes` 에 있어도
 *     「견적서」가 나머지 둘과 똑같이 보여, 메뉴가 「어디로 갈 수 있나」만 말하고
 *     「지금 어디인가」는 말하지 않았다.
 *
 * 🔴 사이드바를 베끼지 않는 까닭은 그대로다. A/S 관리 시스템은 왼쪽 사이드바에
 * 메뉴 열넷을 세우지만 여기는 세 화면이 전부라, 사이드바를 그대로 옮기면 화면
 * 폭의 1/5 을 늘 비워 두게 된다.
 *
 * 🔴 들어갈 수 있는 항목만 받는다. 거르는 일은 부르는 쪽(layout)이 권한 창구로
 * 한다 — 이 조각이 권한을 알면 「보이는데 막힌다」를 만들 자리가 하나 더 생긴다.
 *
 * 항목이 하나도 없으면 아무것도 그리지 않는다. 머리말에 빈 `<nav>` 만 남으면
 * 여백만 벌어지고, 권한이 전혀 없는 사람에게는 그것이 고장으로 읽힌다.
 *
 * 🔴 `"use client"` 를 붙이지 않는다 — 서버 컴포넌트 그대로다. 지금 주소를 아는
 * 일은 단추 하나(NavLink)가 제 안에서 하고, 그 경계는 그 파일에서 끝난다.
 */
export function AppNav({ items }: { items: readonly NavItem[] }) {
  if (items.length === 0) return null;

  return (
    /*
      🔴 이 `<nav>` 자신이 머리말 줄의 flex 항목이다 — 감싸는 `<div>` 를 두지
      않는다(AppHeader 가 그대로 자리에 놓는다).

      🔴 `flex-wrap` 이다. 폰(360px)에서 단추 셋은 ~226px 인데, 같은 줄의 메뉴
      단추와 나가는 단추 둘이 이미 ~297px 을 쓴다. 바깥 머리말도 `flex-wrap`
      이라 이 `<nav>` 는 통째로 아랫줄로 내려가지만, **그 아랫줄에서 셋이 또
      모자랄 수 있다**(폰을 가로로 반 접는 기기·확대 설정). 그때 줄바꿈이
      없으면 flex 가 칸을 min-content 까지 눌러 **단추 안에서 글자를 접는다** —
      "내자 / 정리". 켜 두면 단추 하나가 통째로 다음 줄로 갈 뿐이다.
    */
    <nav aria-label="화면 메뉴" className="flex flex-wrap items-center gap-1">
      {items.map((item) => (
        <NavLink key={item.key} href={item.href}>
          {item.label}
        </NavLink>
      ))}
    </nav>
  );
}
