import type { PartPickerRow } from "@dss/core/ui/inventory/part-picker-rows";
import { partFieldEntries, partFieldLabeledText } from "@dss/core/ui/inventory/part-picker-rows";

/**
 * ============================================================================
 * 견적서 줄이 **고른 부품을 기억한다** (2026-10-17 쓰는 분이 짚은 결함 둘)
 * ============================================================================
 * 부품 고르개를 재고 관리 통로로 옮긴 뒤(커밋 `0b437a6` · 그 뒤 조각 둘) 화면을 보고
 * 쓰는 분이 짚은 것이 둘이다 —
 *
 *  ① 「품명이 **고객사 품명**으로 표시돼야 하는데 그것도 안 되어 있다.」
 *     견적서는 **고객사로 나가는 서류**다. 고객사는 제 이름으로 부품을 부르므로, 우리
 *     품명을 적어 보내면 받는 쪽이 무엇인지 모른다. 그 결정 자체는 이 파일이 아니라
 *     화면이 고르개에 `nameSource="customer"` 를 넘기는 한 줄로 끝난다(QuoteEditForm).
 *  ② 「품명 칸 밑에 있던 **세부 정보가 안 나온다**.」 ① 때문에 더 필요해진 것이다 —
 *     줄에 적히는 이름이 고객사 품명이면, 적어 놓고 보면 **작성자도** 그게 우리 쪽 어느
 *     부품인지 알 수 없다. 그래서 칸 밑에 작은 글씨로 그 부품의 다섯 가지를 적는다.
 *
 * 🔴 **새로 설계한 것이 아니라 옮겨 온 것이다.** A/S 관리 시스템의 **같은 이름 파일**
 *    (`src/components/quotes/quote-part-pick.ts`, 저쪽 커밋 `26d4d4c`)에서 이 사이트에
 *    해당하는 규칙만 옮겼다. 🔵 **안 옮긴 것 하나를 적어 둔다** — 저쪽의 「부품이 바뀌면
 *    단가가 따라간다」와 「상세가 사라지면 단가도 비운다」(2026-10-16 저쪽 요청 ②)는
 *    **저쪽 사용자가 따로 내린 결정**이고 이 사이트에는 그 결정이 없다. 금액을 말없이
 *    바꾸는 규칙이라 「옮기는 김에」 들여오지 않는다 — 이 사이트의 단가 규칙은 지금까지
 *    그대로 「적혀 있으면 덮지 않는다」 하나다(공용 고르개 `partPickUnitPrice` 의 ㉠).
 *
 * ── 🔴 상세는 **밖으로 나가지 않는다** ─────────────────────────────────────
 * 견적서는 고객사로 나가는 종이다. 우리 품명 · 교산 품번 · 도번은 **작성자가 보는 것**이지
 * 고객사가 받는 것이 아니다. 나가는 길은 저장(폼의 `collectFields` →
 * validation/quote-input.ts → db/mutations/quotes.ts) · 인쇄 화면과 미리보기
 * (QuotePrintView) · 엑셀(server/services/quote-workbook.ts)이고, 셋 다 **칸을 하나씩
 * 적어** 옮긴다 — `{ ...row }` 로 통째로 붓는 자리가 없어서 줄에 칸을 더해도 저절로 새지
 * 않는다. 🔴 그래도 **시험으로 못 박는다**(quote-part-pick.test.ts) — 언젠가 누가 편하다고
 * 통째로 붓는 날, 그 한 줄이 고객사에 나가는 서류에 우리 품번을 찍는다.
 *
 * ── 🔴 **베껴 두지 않고 번호로 되짚는다** ──────────────────────────────────
 * 상세를 줄에 적어 두지 않는다. 베껴 두면 재고 관리에서 고객사 품명이나 교산 품번이
 * 채워진 뒤에도 **이 줄만 옛 값**을 보인다. 줄이 들고 있는 것은 **번호 하나**
 * (`inventoryPartNo`)이고, 상세는 그 번호로 받아 온 목록에서 되짚어 그때그때 짓는다
 * (`quotePickedPartOf`). 🔵 그래서 재고 관리에서 목록을 **못 받아 온 날에는 아무것도 안
 * 그린다** — 모르는 것을 지어내지 않는다.
 *
 * ── 🔴 이름을 손으로 고치면 **상세를 안 그린다** ───────────────────────────
 * 줄의 품명은 사람이 손으로도 고치는 자유 글자다. 고친 뒤에도 상세를 그대로 두면 **딴
 * 부품의 품번**을 그 줄의 것으로 읽게 된다 — 적힌 이름이 그 부품에서 온 이름이 아니게
 * 되었으니 상세도 그 줄의 설명이 아니다. 그래서 줄은 **고른 그때 적은 이름**도 함께
 * 기억한다(`pickedPartNameText`).
 * 🔵 **번호는 지우지 않는다.** 이름을 손봐도 **그 줄이 그 부품에서 온 것은 사실**이고,
 *    지우면 다시 열 때 어느 부품에서 왔는지 알 길이 없어진다(ItemRow 의 그 칸 · A/S 의
 *    `quotePartNameEditPatch` 가 같은 말을 한다).
 *
 * ── 🔵 줄이 기억하는 것 둘이 **사는 곳이 다르다** ──────────────────────────
 *  · `inventoryPartNo` — **저장된다**(`quote_items.inventory_part_no`). 다시 열 때 그대로
 *    돌아온다.
 *  · `pickedPartNameText` — **화면에만 산다.** 적어 두지 않는 까닭은, 저장해 두고 그것으로
 *    되살리면 **품명을 손보고 저장한 줄**이 다시 열자마자 두 글자가 어긋나 상세가 안
 *    보이기 때문이다. 다시 열 때는 **줄에 저장된 품명 그대로**를 그 값으로 삼는다
 *    (`quoteRestoredPickedPartName`).
 * ============================================================================
 */

/**
 * 이 규칙이 보는 줄의 칸들. 🔵 폼의 `ItemRow` 전부가 아니라 **쓰는 것만** 받는다 —
 * 줄을 통째로 넘기기 시작하면 언젠가 이 모듈이 수량이나 금액까지 만지게 된다.
 */
export type QuotePartPickRow = {
  partNameText: string;
  /** 재고 관리의 부품 번호(No.)를 **글자로**. 고른 적 없는 줄은 null 이다. */
  inventoryPartNo: string | null;
  /**
   * 고른(또는 담은 · 다시 연) **그때 줄에 적은 이름**. 🔴 **「어느 부품인가」를 재는 값이
   * 아니다** — 그것은 위 번호가 한다. 이 값은 **상세를 아직 그려도 되는가**만 가른다.
   */
  pickedPartNameText: string | null;
};

/**
 * ============================================================================
 * 🔴 고르개가 준 조각을 **줄의 제 칸으로 옮긴다** (2026-10-17 · 폼에서 옮겨 왔다)
 * ============================================================================
 * 공용 고르개는 고른 줄에 부을 조각을 `{ partNameText, partId: option.id, unitPrice? }`
 * 로 돌려준다. 그런데 이 사이트의 `option.id` 는 2026-10-17 부터 **재고 관리의 부품
 * 번호**(`"1"` · `"2"` 같은 정수 글자)다 — 같은 DB 의 `parts.id`(UUID)가 아니다.
 *
 * 🔴 **그대로 부으면 저장이 통째로 막힌다.** 실제로 그랬다 — 고르개로 고른 줄이 하나라도
 *    있는 견적서는 저장할 때 「N번째 부품의 재고 연결을 확인할 수 없습니다」로 거절됐다
 *    (validation/quote-input.ts 의 `isValidQuoteId` 는 UUID 만 통과시킨다).
 * 🔴 **고르개를 고치지 않는다.** 그 조각은 별도 저장소(vendor/dss-core)이고 A/S 도 같이
 *    쓴다. 「`partId` 는 고른 줄의 id 일 뿐, 어디에 저장할지는 폼이 정한다」가 그쪽의
 *    규약이고(part-picker.tsx 의 `partPickPatch` 머리말), 이 함수가 이 사이트의 답이다.
 * 🔵 **`unitPrice` 키는 있을 때만 따라간다** — 고르개의 규약 그대로다. 없는 키를 지어
 *    넣으면(`unitPrice: undefined`) 사람이 적어 둔 금액이 지워진다.
 *
 * 🔵 **폼 안에 있던 함수를 글자 그대로 옮겼다**(앞 조각 보고의 「자리는 quote-part-pick.ts
 *    다」). 번호를 옮기는 동작은 한 글자도 안 바뀌었고, **늘어난 칸은 이름 기억 하나**다 —
 *    번호와 이름 기억은 **같은 순간에** 정해져야 하므로 한 함수 안에서 함께 적는다. 둘로
 *    나누면 어느 날 한쪽만 적히고, 그때 「고르자마자 상세가 안 보이는」 줄이 생긴다.
 * ============================================================================
 */
export type QuotePartPickPatch = {
  partNameText: string;
  /**
   * 🔴 **언제나 null 이다.** 고른 것은 재고 관리의 부품이고 그 번호는 이 DB 의 `parts.id`
   * 가 아니다 — FK 칸에 넣으면 저장이 거절된다.
   */
  partId: null;
  inventoryPartNo: string;
  pickedPartNameText: string;
  unitPrice?: string;
};

export function pickedPartPatch(patch: {
  partNameText: string;
  partId: string;
  unitPrice?: string;
}): QuotePartPickPatch {
  const { partId: inventoryPartNo, ...rest } = patch;
  return { ...rest, partId: null, inventoryPartNo, pickedPartNameText: patch.partNameText };
}

/**
 * ============================================================================
 * 🔴 저장돼 있던 줄을 펼 때 **이름 기억을 되살린다**
 * ============================================================================
 * 되살리지 않으면 저장한 견적서를 다시 열 때마다 상세가 **안 보인다** — 줄에 기억이 없어
 * 「고른 적 없는 줄」로 읽히기 때문이다(사용자가 처음 짚은 그 증상이 다시 생긴다).
 *
 * ── 🔴 그 값은 **줄에 저장된 품명 그대로**다 ──────────────────────────────
 * 「고른 그때의 이름」을 따로 저장하지 않는 까닭이 여기 있다. 옛 이름을 적어 두고 그것으로
 * 되살리면, **품명을 손보고 저장한 줄**은 다시 열자마자 두 글자가 어긋나 상세가 안 보인다.
 * **고치려던 그 증상이 그대로 남는다.** 저장된 품명을 그대로 쓰면 펴는 순간 둘이 같아져
 * 상세가 보인다.
 * 🔵 고친 이름으로 저장한 줄은 다시 열 때 상세가 **다시 보인다** — 화면에서 고치던 동안
 *    감춰 두던 것과 다르지만, 번호는 그 부품이 맞고 이름은 사람이 그렇게 적기로 한 것이다.
 *    「저장된 줄이 어느 부품에서 왔는가」에 답하는 쪽이 작성자에게 쓸모 있다.
 *
 * 🔵 **번호가 없는 줄은 null 이다** — 손으로 적은 줄 · 이 기능이 생기기 전에 저장된 줄이
 *    전부 그렇다. 그런 줄에 이름 기억만 적어 두면 「되짚을 번호가 없는데 상세를 그려도
 *    된다」는 어긋난 상태가 된다.
 * ============================================================================
 */
export function quoteRestoredPickedPartName(line: {
  inventoryPartNo: number | null;
  partNameText: string;
}): string | null {
  return line.inventoryPartNo === null ? null : line.partNameText.trim();
}

/**
 * 줄에 적힌 이름이 **고른 그때의 이름 그대로인가**. 🔵 앞뒤 공백은 같은 것으로 본다 —
 * 칸에 공백 하나가 더 붙었다고 「고쳤다」가 되면 안 된다.
 *
 * 🔴 **`options` 를 보지 않는다.** 이 판정은 **줄이 들고 있는 기억**만으로 끝난다 — 재고
 *    관리에서 목록을 못 받아 온 날에도 「이름을 고쳤는가」의 답은 달라지지 않는다.
 *    목록을 보는 것은 아래 `quotePickedPartOf` 의 **마지막 한 줄**뿐이다.
 */
export function isPickedPartNameKept(row: QuotePartPickRow): boolean {
  return row.pickedPartNameText !== null && row.partNameText.trim() === row.pickedPartNameText;
}

/** 상세 줄의 머리말. 🔵 「고른 부품」이라고 적어야 **적힌 품명과 다른 글자**인 까닭이 읽힌다. */
export const QUOTE_PICKED_PART_PREFIX = "고른 부품";

/**
 * 작성자에게만 보이는 **고른 부품의 상세**.
 *
 * 🔴 **차례는 `PART_FIELD_ORDER` 가 정한다**(공용 묶음 한 곳 — 고객사 품명 · 품명 · 품명2 ·
 *    교산 품번 · 도번). 여기서 다시 적지 않는다. **값이 있는 칸만** 그린다 — 🔴 `-` 만
 *    적힌 칸도 없는 칸이다(`partFieldValue`).
 * 🔴 **이름표를 단다** — 여기는 고르개의 후보 목록과 달리 줄이 하나뿐이라, 값만 이으면
 *    어느 것이 교산 품번이고 어느 것이 도번인지 알 길이 없다.
 * 🔵 **고객사 품명도 적는다** — 바로 위 칸에 같은 글자가 있지만, 그 칸은 사람이 손으로도
 *    고치는 자유 글자다. 둘이 나란히 보여야 「손으로 고쳤다」가 눈에 띈다.
 */
export function quotePickedPartDetail(option: PartPickerRow): string {
  return partFieldLabeledText(partFieldEntries(option));
}

/**
 * 이 줄의 상세로 그릴 부품. 없으면 null 이다 — null 이면 **아무것도 안 그린다**(지어내지
 * 않는다).
 *
 * null 이 되는 경우 셋:
 *  · 아직 고른 적이 없다(손으로 적었거나 · 이 기능이 생기기 전에 저장된 줄을 펼쳤다)
 *  · 🔴 **고른 뒤 이름을 손으로 고쳤다** — 적힌 이름이 그 부품에서 온 이름이 아니게 되었으니
 *    상세도 그 줄의 설명이 아니다. 그대로 두면 **딴 부품의 품번**을 그 줄의 것으로 읽게 된다.
 *    🔵 그래도 번호(`inventoryPartNo`)는 줄에 남아 있다 — 그 줄이 그 부품에서 온 것은
 *       사실이고, 저장에도 그 번호가 실린다.
 *  · 🔵 재고 관리에서 목록을 못 받아 왔다(`options` 가 비어 있다) — 모르는 것을 지어내지
 *    않는다. 🔴 「지금 상세가 안 보인다」와 「이 줄이 어느 부품에서 왔는지 모른다」는 다른
 *    말이다. 통신이 끊긴 날 줄의 기억을 지우면 **돌아오지 않는다.**
 */
export function quotePickedPartOf(
  row: QuotePartPickRow,
  options: readonly PartPickerRow[]
): PartPickerRow | null {
  const inventoryPartNo = row.inventoryPartNo;
  if (inventoryPartNo === null) return null;
  if (!isPickedPartNameKept(row)) return null;
  return options.find((option) => option.id === inventoryPartNo) ?? null;
}
