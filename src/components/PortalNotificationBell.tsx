import { NotificationBell } from "@dss/ui";

import {
  acknowledgeNotificationAction,
  dismissAllNotificationsAction,
  dismissNotificationAction,
} from "@/app/actions/notifications";
import { visibleNotificationKeys } from "@/lib/auth/notification-keys";
import { fetchPortalNotifications } from "@/lib/auth/oidc";

/**
 * 머리말의 알림 종 — **다른 시스템들의** 알림을 그린다.
 *
 * 사내 시스템이 여섯인데(A/S · 포털 · 계측기 · 개선요청 · PO/내자 · 휴가) 종은
 * A/S 에만 있었다. 「어느 시스템에 있든 같은 알림을 본다」를 위해 포털이 모든
 * 시스템에 물어 합쳐 주는 통로를 열었고, 이 조각이 그것을 이 사이트에
 * 끌어온다(부르는 법: dss-auth/docs/사이트-알림-통로.md).
 *
 * ── 🔴 왜 **서버**에서 가져오나 (브라우저가 아니라) ──────────────────────
 * 자격증명이 `client_secret` 이라 브라우저에서는 부를 수 없다. 브라우저에서
 * 가져오려면 이 사이트 안에 중계 통로(route handler)를 하나 더 두고, 거기서
 * 세션을 다시 검증하고, 종을 클라이언트 조각으로 바꾸고, 그 왕복이 도는 동안의
 * 상태까지 다뤄야 한다 — **시크릿을 다루는 자리를 하나 더 만드는** 일이다.
 * 서버에서 부르면 시크릿은 이 프로세스 밖으로 나가지 않고, 종은 지금처럼
 * 자바스크립트 없이도 열리는 서버 조각(@dss/ui 의 `<details>`)으로 남는다.
 *
 * 🔴 그 대신 **모든 화면 이동이 이 왕복만큼 느려지는** 것을 막아야 한다.
 *    그래서 부르는 쪽((app)/layout.tsx)이 이 조각을 `<Suspense>` 로 감싼다 —
 *    머리말과 본문은 먼저 뜨고 종만 나중에 흘러 들어온다. 포털이 느리거나
 *    죽어도 사람이 기다리는 시간은 늘지 않는다. 왕복 자체에도 상한이
 *    걸려 있다(oidc.ts 의 NOTIFICATIONS_TIMEOUT_MS).
 *
 * ── 🔴 다시 묻는 주기는 두지 않는다 ─────────────────────────────────────
 * 브라우저에서 몇 초마다 다시 묻는 장치를 붙이지 않았다. 포털이 이미 30초
 * 캐시를 들고 있어 그보다 자주 물으면 **같은 답**을 받고, 그 장치를 붙이는
 * 순간 위에서 피한 중계 통로가 도로 필요해진다. 종은 화면을 새로 열 때
 * 갱신된다.
 *
 * ── 🔴 확인(onAcknowledge)도 **넘긴다** (2026-10-22) ────────────────────
 * 2026-10-22 까지 여기에는 「**넘기지 않는 이유**」가 적혀 있었다: 여기 오는
 * 알림은 전부 남의 시스템 것이고, 「확인했다」를 적을 수 있는 곳은 그 알림을
 * 만든 시스템뿐이라 **이 사이트에는 적을 자리가 없다**는 것이었다.
 *
 * 🔴 **그 전제가 사라졌다.** 포털에 확인을 적는 통로가 생겼다
 *    (dss-auth 의 /api/integration/notification-acknowledgements, 2026-10-22).
 *    지움과 똑같이 **남의 시스템 줄이어도 여기서 적을 수 있다.**
 *
 * 🔴 **무엇을 없앨지 이 사이트는 판단하지 않는다.** 나가는 것은 열쇠뿐이고,
 *    포털이 제 목록에서 그 줄을 찾아 **내용 지문을 직접 계산**해 적는다.
 *    종에서 빠지는 것은 (기록이 있고 · 지문이 지금 내용과 같고 · 분류가
 *    「정보 확인용」) 셋이 다 맞을 때뿐이다 — 결재 승인·부품 요청처럼
 *    **동작이 필요한 줄은 확인을 적어도 남는다.**
 *
 * 🔴 ✕(onDismiss)와 **다른 일**이다. ✕ 는 「지금은 그만 보겠다」라
 *    재로그인하면 돌아오고, 누름은 「해소됐다」라 돌아오지 않는다.
 *    **두 단추를 한쪽으로 합치지 말 것** — 포털의 표도 통로도 둘이다.
 *
 * 🔵 여기서는 **제 줄과 남의 줄을 가르지 않는다.** 이 사이트에는 제 알림이
 *    한 건도 없어서 오는 줄이 전부 포털 것이다(아래 본문 주석).
 *    2026-10-22 까지 여기에는 "제 알림이 생기면 여기서 갈라야 한다 — 제 줄의
 *    확인은 포털이 아니라 이 사이트에 적어야 한다(포털은 부른 사이트 자신의
 *    알림을 모른다). 지금 그대로 두면 제 줄의 확인이 포털에서 조용히
 *    버려진다"라고 적혀 있었다.
 *
 * 🔴 **그 전제가 같은 날 사라졌다.** dss-auth 커밋 3dd31bf(2026-10-22)로
 *    포털이 부른 사이트 자신의 알림도 함께 묻는다 — 다만 그 답은 여전히
 *    `items`·`count`·`sources` 에는 **담지 않고**(되돌기·30초 캐시 지연·포털이
 *    죽어도 보여야 하는 세 까닭은 그대로다), **확인(`acknowledged`) 열쇠를
 *    가리는 데만** 쓴다. 확인 통로는 전체 목록을 보고 포털이 직접 지문을
 *    계산해 `acknowledged` 를 내준다 — `dismissed` 와 **별개 칸**이고 수명이
 *    달라(✕ 는 로그아웃하면 돌아오고 ✓ 는 안 돌아온다) **합치면 안 된다**
 *    (dss-auth/docs/사이트-알림-통로.md 의 `acknowledged` 절).
 *
 * 🔴 **그래서 제 알림이 생기면** "갈라서 이 사이트에 확인을 적는다"가 아니라
 *    **"제 줄도 포털로 보내고, 돌려받은 `acknowledged` 열쇠로 제 줄을
 *    거른다"가 맞는 길이다.** 본보기가 있다 — dss-inventory 가 오늘 그렇게
 *    했다.
 *
 * 🔵 다만 **모든 집이 그렇게 하는 것은 아니다.** 휴가는 제 줄이 결재 대기뿐이라
 *    숨길 길을 열 필요가 없고, 게시판은 글을 열면 사라지는 다른 길이 이미
 *    있어 둘 다 일부러 제 줄을 포털로 안 보낸다 — "무조건 보낸다"는 아니다.
 *
 * 🔴 확인이 **실패해도 그 줄이 향하던 화면으로 가는 것을 막지 않는다.**
 *    이동은 평범한 <a href> 가 하고, @dss/ui 가 이 함수를 try 로 감싸
 *    던져도 밖으로 내보내지 않는다(BellBehavior.tsx 의 notifyAcknowledged).
 *    서버 액션 쪽도 제 손으로 한 번 더 삼킨다 — 그 성질에 기대지 않는다.
 *
 * ── 🔴 지우기(onDismiss)는 **넘긴다** — 확인과 다른 일이다 ──────────────
 * 「확인했다」는 그 알림을 만든 시스템에만 적을 수 있지만, 「그만 보겠다」는
 * **포털**에 적힌다(2026-10-19). 그래서 남의 시스템 줄이어도 이 사이트에서
 * 지울 수 있고, 한 번 지우면 사내 시스템 **전부의 종**에서 사라진다. 적는
 * 자리는 서버 액션이다 — 평범한 함수는 클라이언트 경계를 건너지 못하고,
 * 중계 통로를 뚫으면 위 문단에서 피한 「시크릿을 다루는 자리」가 늘어난다
 * (app/actions/notifications.ts).
 *
 * 🔴 `canDismiss` 는 넘기지 않는다 = **모든 줄에 ✕ 가 선다.** 그래도 되는
 *    까닭: 가려야 하는 것은 「처리해야 사라지는 제 할 일」인데(A/S 가 그렇다)
 *    여기에는 **제 줄이 아예 없다.** 남의 시스템 줄은 어느 것이든 「내 종에서
 *    그만 보겠다」가 뜻이 통한다.
 *
 * ── 🔴 「보이는 알림 지우기」(onDismissAll)도 **넘긴다** (2026-10-20) ─────
 * 줄이 여럿이면 ✕ 를 여러 번 눌러야 했다. 그 단추는 A/S 에만 있었는데(제 손으로
 * 만든 것이었다), 이제 @dss/ui 가 **단추도 글자도 개수도** 그린다 — 사이트가
 * 하는 일은 함수를 넘기는 것뿐이다(그쪽 README 「보이는 알림 지우기」 절).
 *
 * 🔴 그 자리는 `() => void` 로 **인자를 안 받는데** 지울 열쇠 목록을 아는 것은
 *    이쪽이다. 그래서 **값을 미리 묶어** 넘긴다(`…bind(null, 열쇠들)`). 묶은
 *    것도 여전히 서버 액션이라 경계를 건넌다 — 평범한 화살표 함수는 못 건넌다
 *    (이 조각에 "use client" 가 없는 것이 그 짝이다).
 */
export async function PortalNotificationBell({ subject }: { subject: string }) {
  // 🔴 던지지 않는다. 포털이 죽었든 우리를 거절했든 빈 목록이 온다.
  const feed = await fetchPortalNotifications(subject);

  // 🔴 이 사이트에는 **자체 알림이 없다.** (2026-09-21 확인 — 견적서 결재
  //    알림은 **A/S 의 종**에 계속 뜨고 링크 주소만 이쪽으로 바뀐다. 설계서
  //    PO_DOMESTIC_SPLIT_DESIGN.md F절 2번 · lib/navigation.ts 주석. 이 사이트가
  //    제 종에 쌓는 알림은 한 건도 없다.) 그래서 받은 것이 곧 전부다 — A/S 의
  //    결재 알림도 포털을 거쳐 여기 그대로 실려 온다.
  //    자체 알림이 생기면 여기서 `[...내것, ...feed.items]` 로 이어 붙이고
  //    개수도 더한다 — 포털은 부른 사이트 자신의 알림을 빼고 주기 때문이다.
  //
  // 개수는 포털이 센 값 그대로 넘긴다(다시 세지 않는다 — @dss/ui README 7절).
  // 목록이 비면 그 조각이 스스로 null 이라 머리말에 종 자체가 생기지 않는다.
  //
  // 🔴 colorScheme 은 넘기지 않는다. 이 사이트는 globals.css 에서
  //    color-scheme: light 로 고정이고, 기본값 "host" 는 조상에 .dark 가 있을
  //    때만 어두워지므로 그대로 두는 것이 옳다(@dss/ui README 4·7절).
  // 🔴 `onDismiss` 를 **넘겼을 때만** 줄마다 ✕ 가 그려진다(@dss/ui). 넘기는
  //    것은 서버 액션이라 번들에는 이름표만 나가고 `client_secret` 은 서버에
  //    남는다 — 이 조각에 "use client" 가 없는 것이 그 판단의 짝이다.
  //
  // 🔴 개수(배지)는 **줄이지 않는다.** 지운 뒤의 목록도 개수도 다음 렌더에서
  //    포털이 다시 세어 준다 — 포털은 지운 줄을 items 에서 빼면서 count 도
  //    함께 줄여 보낸다. 여기서 미리 빼면 포털이 센 값과 어긋난다.
  // ── 🔴 일괄 지우기에 넘길 열쇠 — **지금 그리는 줄 전부** ────────────────
  // 🔵 이 사이트에는 제 알림이 없으므로(바로 위) 포털에서 온 이 목록이 곧
  //    종에 있는 전부다. 자체 알림이 생기면 이어 붙인 뒤의 목록으로 묶어야
  //    한다 — 안 그러면 단추가 제 알림은 안 지운다.
  //
  // 🔴 `visibleNotificationKeys` 가 **그릴 수 없는 주소의 줄을 뺀다.** 종도
  //    그 줄을 안 그리고 단추에 적는 수도 그렇게 남은 줄 수라, 여기서 빼지
  //    않으면 「3건」을 눌렀는데 4건이 지워진다(그 함수 주석).
  // 🔴 묶는 일은 **그릴 때마다** 한다 — 이 조각이 그려지는 순간의 목록이
  //    곧 사람이 보는 목록이다.
  const dismissAll = dismissAllNotificationsAction.bind(
    null,
    visibleNotificationKeys(feed.items),
  );

  return (
    <NotificationBell
      items={feed.items}
      count={feed.count}
      onAcknowledge={acknowledgeNotificationAction}
      onDismiss={dismissNotificationAction}
      onDismissAll={dismissAll}
    />
  );
}
