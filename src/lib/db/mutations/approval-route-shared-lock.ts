import "server-only";

import { sql } from "drizzle-orm";
import type { db } from "@/lib/db";

/**
 * ============================================================================
 * 🔴 결재선 **공유** 잠금 하나 — 읽는 쪽이 쓰는 잠금만 여기 있다
 * ============================================================================
 * 🔴 **이 파일에는 결재선을 고치는 것이 하나도 없다.** 파일 이름이
 * `shipment-approval-routes.ts` 가 아닌 것은 일부러다 — 그 이름이면 「설정을
 * 가져왔다」로 읽힌다. 결재선 설정(누가 몇 번째로 결재하는가)은 **A/S 에서만**
 * 한다(2026-09-28 사용자 결정). 이 사이트는 결재선을 읽어 결재 행을 만들 뿐이다.
 *
 * ── 🔴 열쇠 문자열이 A/S 와 **글자 하나까지** 같아야 한다 ────────────────
 * 이 도우미와 열쇠는 A/S 관리 시스템의
 *
 *     src/lib/db/mutations/shipment-approval-routes.ts
 *       :110       const ROUTE_LOCK_KEY = "shipment_approval_routes:current";
 *       :137-139   acquireShipmentApprovalRouteSharedLock()
 *
 * 에서 그대로 가져왔다. 🔴 **저쪽 `ROUTE_LOCK_KEY` 와 글자가 같아야 한다.** 저쪽
 * 원본 주석이 그 까닭을 그대로 말한다 — 한쪽이 문자열을 따로 적으면 **글자 하나만
 * 달라도 두 잠금이 서로를 보지 못하고, 그 어긋남은 아무 오류도 내지 않는다.**
 *
 * 두 저장소가 **같은 DB**(dss_as)를 본다. 열쇠가 갈라지면 「결재선을 읽은 뒤
 * A/S 에서 계정 삭제가 커밋되고, 그다음 지워진 사람에게 결재 행이 가는」 틈이
 * **이 사이트에서만** 열린다. 삭제의 재지정은 커밋되지 않은 행을 볼 수 없으므로,
 * 그렇게 생긴 행은 최고관리자 비상구로만 풀린다.
 *
 * 그래서 열쇠는 **이 저장소에서 여기 한 곳에만** 적고, 글자가 맞는지는
 * `src/lib/db/approval-route-read-only.test.ts` 가 그대로 단언한다.
 *
 * ── 🔴 배타 잠금은 **가져오지 않았다** ──────────────────────────────────
 * 저쪽 `:120-122` 의 `acquireShipmentApprovalRouteLock`(배타)은 결재선을
 * **고치는 쪽**(결재선 저장 · 사용자 계정 삭제)이 쓴다. 이 사이트에는 그 일이
 * 없으므로 그 이름이 여기 있으면 안 된다 — 위 시험이 그것도 잰다.
 *
 * ── 쓰는 법 ─────────────────────────────────────────────────────────────
 * 공유 잠금끼리는 서로 막지 않으므로 요청 · 결정끼리는 예전처럼 동시에 돈다.
 * 막는 상대는 배타 잠금을 쥔 둘(결재선 저장 · 계정 삭제)뿐이다.
 *
 * 🔴 트랜잭션의 **첫 잠금**이어야 한다 — 다른 행을 먼저 잠근 채로 이것을
 * 기다리면, 배타 잠금을 쥔 삭제가 그 행을 기다리는 순간 교착이 된다.
 *
 * 부르는 곳은 아직 없다. 조각 B(견적서 결재 서버 쪽)의
 * `mutations/quote-approvals.ts` 가 자기 트랜잭션 첫 줄에서 부른다.
 * ============================================================================
 */

type Tx = Parameters<Parameters<typeof db.transaction>[0]>[0];

/**
 * advisory 잠금의 고정 열쇠. 용도(scope)로 나누지 않는다 — 저쪽과 같은 한 줄로
 * 세우기 위한 값이라, 나누는 순간 저쪽과 짝이 맞지 않는다.
 *
 * 🔴 **이 저장소에서 이 문자열이 적힌 유일한 곳이다.**
 */
const ROUTE_LOCK_KEY = "shipment_approval_routes:current";

/**
 * 결재선 **공유** 잠금을 건다 — 트랜잭션 안에서 부르고, 트랜잭션이 끝나면
 * 저절로 풀린다.
 *
 * 결재선을 **읽어** 결재 행을 만드는 쪽(승인 요청 · 결재 결정)이 트랜잭션의 첫
 * 잠금으로 건다. 이것이 없으면 「결재선을 읽은 뒤 삭제가 커밋되고, 그다음에
 * 지워진 사람에게 지정된 행을 넣는」 틈이 생긴다.
 */
export async function acquireShipmentApprovalRouteSharedLock(tx: Tx): Promise<void> {
  await tx.execute(sql`SELECT pg_advisory_xact_lock_shared(hashtextextended(${ROUTE_LOCK_KEY}, 0))`);
}
