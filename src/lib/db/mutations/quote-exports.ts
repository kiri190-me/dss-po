import "server-only";

import { db } from "@/lib/db";
import { insertAuditLog } from "./audit-logs";

/**
 * ============================================================================
 * 견적서 파일을 내보낸 사실을 감사 로그에 한 줄 남긴다 (조각 3c-2)
 * ============================================================================
 * 🔴 A/S 관리 시스템의 같은 이름 파일과 **같은 한 줄을 같은 표에 쓴다**(저쪽
 * `src/lib/db/mutations/quote-exports.ts`). 감사 표는 두 사이트가 함께 쓰는 `dss_as` 의
 * `audit_logs` 한 표이므로(./audit-logs.ts 머리말), 같은 일에 다른 종류를 남기면 「누가
 * 언제 어느 견적서를 뽑아 갔나」에 답하는 자리가 둘로 갈린다. 그래서 **종류 ·
 * 대상 · 담는 값을 저쪽과 한 글자도 다르게 두지 않았다.**
 *
 * ── 왜 남기는가 ─────────────────────────────────────────────────────────
 * 이 파일에는 **법인 직인이 찍혀 있고 거래 금액이 적혀 있다.** 고객사에 실제로 나가는
 * 문서이므로, 누가 언제 어느 견적서를 뽑아 갔는지는 남아 있어야 한다. 받기 통로가
 * 아무것도 바꾸지 않는데도(READ 권한으로 충분한 까닭 — 라우트 머리말) 감사만은 남기는
 * 것이 그 때문이다.
 *
 * ── FILE_DOWNLOAD 가 아니라 EXCEL_EXPORT 다 ─────────────────────────────
 * FILE_DOWNLOAD 는 **저장돼 있던 파일을 꺼내 간 일**이다. 이쪽은 요청을 받은 순간
 * 만들어 낸 문서라, 디스크에 그런 파일이 있었던 적이 없다 — 감사 기록을 읽는 사람이
 * "그 파일을 찾아보자"고 했을 때 찾을 것이 없는 종류다. 둘을 같은 이름으로 남기면
 * 그 구분이 사라진다.
 *
 * ── 값은 담지 않는다 ────────────────────────────────────────────────────
 * 금액도 품명도 신고증상도 적지 않는다. **무엇을 누가 가져갔는지는 견적서 id 와
 * 발행번호가 이미 답한다**(quotes 표를 보면 나머지가 전부 있다). 감사 로그는 3년 보관
 * 대상이라, 거기에 사본을 한 벌 더 만들면 지워야 할 자료가 두 곳이 된다.
 *
 * ── 🔴 트랜잭션을 여는 것은 이 파일이다 ─────────────────────────────────
 * `insertAuditLog` 는 **이미 열린 트랜잭션을 받는다** — 그 표는 언제나 기록하려는
 * 작업과 같은 트랜잭션 안에서 쓰이기 때문이다(./audit-logs.ts). 내보내기는 함께 쓸
 * 작업이 없어(바꾸는 것이 없다) 이 한 줄만을 위한 트랜잭션을 여기서 연다. 라우트가
 * `db.transaction` 을 직접 부르지 않는 것은 이 저장소의 쓰기가 전부 `mutations/` 를
 * 지나기 때문이다 — 그 규칙이 `import "server-only"` 를 여기 붙여 둔 자리이기도 하다.
 * ============================================================================
 */
export async function recordQuoteExport(params: {
  quoteId: string;
  quoteNumber: string;
  actorUserId: string;
}): Promise<void> {
  await db.transaction(async (tx) => {
    await insertAuditLog(tx, {
      actorUserId: params.actorUserId,
      actionType: "EXCEL_EXPORT",
      targetEntity: "quotes",
      targetRecordId: params.quoteId,
      // 내보내기는 상태를 바꾸지 않으므로 previousValue 가 없다.
      newValue: { quoteNumber: params.quoteNumber },
    });
  });
}
