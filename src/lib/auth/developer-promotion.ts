/**
 * ============================================================================
 * 개발자 승격은 **더하기**다
 * ============================================================================
 *
 *     개발자의 권한 = 진짜 역할의 권한 ∪ 최고관리자의 권한
 *
 * 🔴 A/S 관리 시스템의 `lib/auth/developer-promotion.ts` 와 **같은 규칙**이다.
 * `users.is_developer` 는 두 사이트가 함께 읽는 한 칸이므로(vendor/dss-core 의
 * users.ts) 해석도 같아야 한다 — 한쪽에서만 승격되면 같은 사람이 두 사이트에서
 * 다른 권한을 갖는다.
 *
 * ── 왜 갈아치우기가 아닌가 ──────────────────────────────────────────────
 * 처음 구현은 역할을 갈아치우는 방식이었다(`isDeveloper ? "SUPER_ADMIN" : role`).
 * 그러면 **최고관리자가 그 사람의 진짜 역할보다 낮은 자리에서 개발자가 되는 것이
 * 손해**가 된다. `role_permissions` 표는 화면에서 사람이 바꾸는 값이라 실제로
 * 그렇게 될 수 있다 — 최고관리자의 어떤 영역을 영업보다 낮게 저장해 두면,
 * 갈아치우기 방식에서는 개발자 표시를 켠 영업이 그 영역에서 권한을 잃는다.
 *
 * 더하기로 두면 그 일이 구조적으로 일어날 수 없다. 수준(level)을 다루는 이
 * 사이트에서 그 모양은 **둘 중 높은 쪽**이다(permission-resolver.ts).
 *
 * ── 승격이 인자인 이유 ──────────────────────────────────────────────────
 * 판정 함수가 세션을 몰래 읽지 않는다. 그러면 역할을 훑으며 같은 창구를 부르는
 * 자리가 개발자에게만 전부 「모든 권한」으로 보이고, 그 방향은 **열리는 쪽으로**
 * 실패한다. 인자로 받으면 호출부를 빠뜨려도 그 자리만 승격이 안 될 뿐이다.
 * ============================================================================
 */
import type { Role } from "./session";

/** 개발자 표시가 켜진 계정이 **함께** 갖는 역할. */
export const DEVELOPER_PROMOTED_ROLE: Role = "SUPER_ADMIN";
